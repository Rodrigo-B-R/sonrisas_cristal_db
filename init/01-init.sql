-- Se ejecuta solo la primera vez que se crea la base de datos.
-- Modelo segun el diagrama de image.png (README).
-- Las tablas se crean en orden de dependencia y las FK se agregan al final.

-- ===================== Catalogos =====================

CREATE TABLE rol (
    id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(255) NOT NULL
);

CREATE TABLE puesto (
    id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(255) NOT NULL
);

CREATE TABLE causa_baja (
    id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(255) NOT NULL
);

CREATE TABLE turno (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre       VARCHAR(255) NOT NULL,
    hora_entrada TIME(0) WITHOUT TIME ZONE NOT NULL,
    hora_salida  TIME(0) WITHOUT TIME ZONE NOT NULL
);

CREATE TABLE ubicacion (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre    VARCHAR(255) NOT NULL,
    latitud   DOUBLE PRECISION NOT NULL,
    longitud  DOUBLE PRECISION NOT NULL,
    "precision" BIGINT NOT NULL
);

CREATE TABLE estancia (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_ubicacion BIGINT NOT NULL,
    nombre       VARCHAR(255) NOT NULL
);

CREATE TABLE sala (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre          VARCHAR(255) NOT NULL,
    minimo_personal INTEGER NOT NULL,
    id_estancia     BIGINT NOT NULL
);

-- ===================== Usuarios =====================

CREATE TABLE usuario (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre      VARCHAR(255) NOT NULL,
    "contraseña" VARCHAR(255) NOT NULL,
    clave       VARCHAR(255) NOT NULL,
    id_rol      BIGINT NOT NULL,
    id_puesto   BIGINT NOT NULL,
    correo      VARCHAR(255) NOT NULL,
    celular     VARCHAR(255) NOT NULL,
    esta_activo BOOLEAN NOT NULL,
    id_estancia BIGINT NOT NULL
);

CREATE TABLE movimiento_usuario (
    id                        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario_del_movimiento BIGINT NOT NULL,
    tipo                      VARCHAR(255) NOT NULL,
    fecha                     DATE NOT NULL,
    id_usuario_que_movio      BIGINT NOT NULL,
    observaciones             VARCHAR(255),
    id_causa_baja             BIGINT,  -- solo aplica a bajas
    id_estancia_origen        BIGINT,  -- no aplica a altas
    id_estancia_destino       BIGINT   -- no aplica a bajas
);

CREATE TABLE aviso (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    asunto           VARCHAR(255) NOT NULL,
    tipo_aviso       VARCHAR(255) NOT NULL,
    id_usuario_envia BIGINT NOT NULL,
    mensaje          VARCHAR(255) NOT NULL
);

CREATE TABLE aviso_usuario (
    id_aviso   BIGINT NOT NULL,
    id_usuario BIGINT NOT NULL,
    leido      BOOLEAN NOT NULL DEFAULT FALSE,
    leido_en   TIMESTAMP(0) WITH TIME ZONE,  -- hora en que confirmo la lectura
    PRIMARY KEY (id_aviso, id_usuario)
);

-- ===================== Registros =====================

CREATE TABLE horario (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario    BIGINT NOT NULL,
    vigente_hasta DATE NOT NULL,
    vigente_desde DATE NOT NULL
);

CREATE TABLE horario_dia (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dia_de_semana VARCHAR(255) NOT NULL,
    id_horario    BIGINT NOT NULL,
    id_turno      BIGINT NOT NULL,
    id_sala       BIGINT NOT NULL
);

CREATE TABLE registro_entradas (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario_entrada  BIGINT NOT NULL,
    fecha_hora_entrada  TIMESTAMP(0) WITH TIME ZONE NOT NULL,
    fecha_hora_salida   TIMESTAMP(0) WITH TIME ZONE,  -- NULL hasta que sale
    id_ubicacion        BIGINT NOT NULL,
    origen_registro     VARCHAR(255) NOT NULL,
    id_usuario_registro BIGINT NOT NULL,
    id_sala             BIGINT NOT NULL,
    uuid                UUID NOT NULL,
    id_turno            BIGINT NOT NULL,
    dentro_de_zona      BOOLEAN NOT NULL  -- FALSE = "fuera de zona", la Responsable lo revisa
);

CREATE TABLE asistencia (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario_que_asistio BIGINT NOT NULL,
    estado                 VARCHAR(255) NOT NULL,
    fecha                  DATE NOT NULL,
    id_usuario_registro    BIGINT NOT NULL,
    id_estancia            BIGINT NOT NULL,
    motivo                 VARCHAR(255)
);

-- ===================== Llaves foraneas =====================

ALTER TABLE estancia
    ADD CONSTRAINT estancia_id_ubicacion_fkey FOREIGN KEY (id_ubicacion) REFERENCES ubicacion (id);

ALTER TABLE sala
    ADD CONSTRAINT sala_id_estancia_fkey FOREIGN KEY (id_estancia) REFERENCES estancia (id);

ALTER TABLE usuario
    ADD CONSTRAINT usuario_id_rol_fkey      FOREIGN KEY (id_rol)      REFERENCES rol (id),
    ADD CONSTRAINT usuario_id_puesto_fkey   FOREIGN KEY (id_puesto)   REFERENCES puesto (id),
    ADD CONSTRAINT usuario_id_estancia_fkey FOREIGN KEY (id_estancia) REFERENCES estancia (id);

ALTER TABLE movimiento_usuario
    ADD CONSTRAINT movimiento_usuario_id_usuario_del_movimiento_fkey FOREIGN KEY (id_usuario_del_movimiento) REFERENCES usuario (id),
    ADD CONSTRAINT movimiento_usuario_id_usuario_que_movio_fkey      FOREIGN KEY (id_usuario_que_movio)      REFERENCES usuario (id),
    ADD CONSTRAINT movimiento_usuario_id_causa_baja_fkey             FOREIGN KEY (id_causa_baja)             REFERENCES causa_baja (id),
    ADD CONSTRAINT movimiento_usuario_id_estancia_origen_fkey        FOREIGN KEY (id_estancia_origen)        REFERENCES estancia (id),
    ADD CONSTRAINT movimiento_usuario_id_estancia_destino_fkey       FOREIGN KEY (id_estancia_destino)       REFERENCES estancia (id);

ALTER TABLE aviso
    ADD CONSTRAINT aviso_id_usuario_envia_fkey FOREIGN KEY (id_usuario_envia) REFERENCES usuario (id);

ALTER TABLE aviso_usuario
    ADD CONSTRAINT aviso_usuario_id_aviso_fkey   FOREIGN KEY (id_aviso)   REFERENCES aviso (id),
    ADD CONSTRAINT aviso_usuario_id_usuario_fkey FOREIGN KEY (id_usuario) REFERENCES usuario (id);

ALTER TABLE horario
    ADD CONSTRAINT horario_id_usuario_fkey FOREIGN KEY (id_usuario) REFERENCES usuario (id);

ALTER TABLE horario_dia
    ADD CONSTRAINT horario_dia_id_horario_fkey FOREIGN KEY (id_horario) REFERENCES horario (id),
    ADD CONSTRAINT horario_dia_id_turno_fkey   FOREIGN KEY (id_turno)   REFERENCES turno (id),
    ADD CONSTRAINT horario_dia_id_sala_fkey    FOREIGN KEY (id_sala)    REFERENCES sala (id);

ALTER TABLE registro_entradas
    ADD CONSTRAINT registro_entradas_id_usuario_entrada_fkey  FOREIGN KEY (id_usuario_entrada)  REFERENCES usuario (id),
    ADD CONSTRAINT registro_entradas_id_usuario_registro_fkey FOREIGN KEY (id_usuario_registro) REFERENCES usuario (id),
    ADD CONSTRAINT registro_entradas_id_ubicacion_fkey        FOREIGN KEY (id_ubicacion)        REFERENCES ubicacion (id),
    ADD CONSTRAINT registro_entradas_id_sala_fkey             FOREIGN KEY (id_sala)             REFERENCES sala (id),
    ADD CONSTRAINT registro_entradas_id_turno_fkey            FOREIGN KEY (id_turno)            REFERENCES turno (id);

ALTER TABLE asistencia
    ADD CONSTRAINT asistencia_id_usuario_que_asistio_fkey FOREIGN KEY (id_usuario_que_asistio) REFERENCES usuario (id),
    ADD CONSTRAINT asistencia_id_usuario_registro_fkey    FOREIGN KEY (id_usuario_registro)    REFERENCES usuario (id),
    ADD CONSTRAINT asistencia_id_estancia_fkey            FOREIGN KEY (id_estancia)            REFERENCES estancia (id);

-- ===================== Restricciones de integridad =====================

-- Valores permitidos
ALTER TABLE movimiento_usuario
    ADD CONSTRAINT movimiento_usuario_tipo_check CHECK (tipo IN ('alta', 'baja', 'traslado')),
    -- cada tipo exige (y solo permite) los campos que le corresponden
    ADD CONSTRAINT movimiento_usuario_campos_por_tipo_check CHECK (
        (tipo = 'alta'     AND id_estancia_destino IS NOT NULL AND id_estancia_origen IS NULL     AND id_causa_baja IS NULL) OR
        (tipo = 'baja'     AND id_estancia_origen  IS NOT NULL AND id_estancia_destino IS NULL    AND id_causa_baja IS NOT NULL) OR
        (tipo = 'traslado' AND id_estancia_origen  IS NOT NULL AND id_estancia_destino IS NOT NULL AND id_causa_baja IS NULL
                           AND id_estancia_origen <> id_estancia_destino)
    );

ALTER TABLE horario_dia
    ADD CONSTRAINT horario_dia_dia_de_semana_check
        CHECK (dia_de_semana IN ('lunes','martes','miercoles','jueves','viernes','sabado','domingo')),
    ADD CONSTRAINT horario_dia_unico UNIQUE (id_horario, dia_de_semana, id_turno, id_sala);

-- Coherencia de datos
ALTER TABLE horario
    ADD CONSTRAINT horario_vigencia_check CHECK (vigente_desde <= vigente_hasta);

ALTER TABLE registro_entradas
    ADD CONSTRAINT registro_entradas_salida_check
        CHECK (fecha_hora_salida IS NULL OR fecha_hora_salida > fecha_hora_entrada),
    ADD CONSTRAINT registro_entradas_uuid_unico UNIQUE (uuid);

ALTER TABLE ubicacion
    ADD CONSTRAINT ubicacion_latitud_check   CHECK (latitud  BETWEEN -90  AND 90),
    ADD CONSTRAINT ubicacion_longitud_check  CHECK (longitud BETWEEN -180 AND 180),
    ADD CONSTRAINT ubicacion_precision_check CHECK ("precision" >= 0);

ALTER TABLE sala
    ADD CONSTRAINT sala_minimo_personal_check CHECK (minimo_personal >= 0);

-- Un usuario no se identifica por datos repetidos
ALTER TABLE usuario
    ADD CONSTRAINT usuario_correo_unico UNIQUE (correo),
    ADD CONSTRAINT usuario_clave_unica  UNIQUE (clave);

-- Una asistencia por persona, estancia y dia
ALTER TABLE asistencia
    ADD CONSTRAINT asistencia_unica UNIQUE (id_usuario_que_asistio, id_estancia, fecha);

-- Valores permitidos segun las opciones que ofrece la app
ALTER TABLE asistencia
    ADD CONSTRAINT asistencia_estado_check CHECK (estado IN ('presente', 'retardo', 'falta', 'incidencia')),
    ADD CONSTRAINT asistencia_motivo_check CHECK (motivo IS NULL OR motivo IN ('enfermedad', 'permiso', 'personal', 'transporte', 'otro')),
    -- falta e incidencia exigen motivo
    ADD CONSTRAINT asistencia_motivo_requerido_check CHECK (estado NOT IN ('falta', 'incidencia') OR motivo IS NOT NULL);

ALTER TABLE aviso
    ADD CONSTRAINT aviso_tipo_aviso_check CHECK (tipo_aviso IN ('cambio_horario', 'reunion', 'recordatorio', 'urgente'));

ALTER TABLE registro_entradas
    ADD CONSTRAINT registro_entradas_origen_check CHECK (origen_registro IN ('app', 'responsable'));

-- leido y leido_en siempre coherentes
ALTER TABLE aviso_usuario
    ADD CONSTRAINT aviso_usuario_leido_check CHECK (leido = (leido_en IS NOT NULL));
