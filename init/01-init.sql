-- ===================== Auditoria automatica =====================

-- Registra cada INSERT/UPDATE/DELETE de las tablas de asistencia.
-- La API debe fijar el autor al inicio de cada transaccion:
--     SET LOCAL app.id_usuario = '<id del usuario autenticado>';
-- SECURITY DEFINER: escribe como el dueño, asi api_user no necesita (ni tiene)
-- permiso de INSERT directo sobre auditoria y no puede falsificar filas.
CREATE FUNCTION registrar_auditoria() RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE
    v_usuario BIGINT := NULLIF(current_setting('app.id_usuario', true), '')::BIGINT;
BEGIN
    IF TG_OP = 'INSERT' THEN
        INSERT INTO auditoria (id_usuario, accion, tabla, id_registro, datos_nuevos)
        VALUES (v_usuario, TG_OP, TG_TABLE_NAME, NEW.id, to_jsonb(NEW));
    ELSIF TG_OP = 'UPDATE' THEN
        INSERT INTO auditoria (id_usuario, accion, tabla, id_registro, datos_anteriores, datos_nuevos)
        VALUES (v_usuario, TG_OP, TG_TABLE_NAME, NEW.id, to_jsonb(OLD), to_jsonb(NEW));
    ELSE
        INSERT INTO auditoria (id_usuario, accion, tabla, id_registro, datos_anteriores)
        VALUES (v_usuario, TG_OP, TG_TABLE_NAME, OLD.id, to_jsonb(OLD));
    END IF;
    RETURN NULL;  -- trigger AFTER: el valor de retorno se ignora
END $$;

CREATE TRIGGER registro_entradas_auditoria AFTER INSERT OR UPDATE OR DELETE ON registro_entradas
    FOR EACH ROW EXECUTE FUNCTION registrar_auditoria();
CREATE TRIGGER asistencia_auditoria AFTER INSERT OR UPDATE OR DELETE ON asistencia
    FOR EACH ROW EXECUTE FUNCTION registrar_auditoria();

-- Append-only: rechaza modificar, borrar o vaciar la auditoria.
CREATE FUNCTION auditoria_inmutable() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION 'auditoria es append-only: % no permitido', TG_OP;
END $$;

CREATE TRIGGER auditoria_no_modificar BEFORE UPDATE OR DELETE ON auditoria
    FOR EACH ROW EXECUTE FUNCTION auditoria_inmutable();
CREATE TRIGGER auditoria_no_vaciar BEFORE TRUNCATE ON auditoria
    FOR EACH STATEMENT EXECUTE FUNCTION auditoria_inmutable();
