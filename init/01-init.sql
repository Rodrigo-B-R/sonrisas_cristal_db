-- Se ejecuta solo la primera vez que se crea la base de datos.
-- Modelo segun el diagrama de image.png (README).
-- Las tablas se crean en orden de dependencia y las FK se agregan al final.

-- ===================== Catalogos =====================

CREATE TABLE rol (
    id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(255) NOT NULL
);

CREATE TABLE puesto (
    id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(255) NOT NULL
);

CREATE TABLE causa_baja (
    id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(255) NOT NULL
);

CREATE TABLE motivo_ausencia (
    id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    descripcion VARCHAR(255) NOT NULL UNIQUE
);

CREATE TABLE turno (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre       VARCHAR(255) NOT NULL,
    hora_entrada TIME(0) WITHOUT TIME ZONE NOT NULL,
    hora_salida  TIME(0) WITHOUT TIME ZONE NOT NULL
);

CREATE TABLE ubicacion (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre    VARCHAR(255) NOT NULL,
    latitud   DOUBLE PRECISION NOT NULL,
    longitud  DOUBLE PRECISION NOT NULL,
    "precision" BIGINT NOT NULL
);

CREATE TABLE estancia (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_ubicacion BIGINT NOT NULL,
    nombre       VARCHAR(255) NOT NULL
);

CREATE TABLE sala (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre          VARCHAR(255) NOT NULL,
    minimo_personal INTEGER NOT NULL,
    id_estancia     BIGINT NOT NULL
);

-- ===================== Usuarios =====================

CREATE TABLE usuario (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre      VARCHAR(255) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    usuario_login       VARCHAR(255) NOT NULL,
    id_rol      BIGINT NOT NULL,
    id_puesto   BIGINT NOT NULL,
    correo      VARCHAR(255) NOT NULL,
    celular     VARCHAR(255) NOT NULL,
    esta_activo BOOLEAN NOT NULL,
    id_estancia BIGINT NOT NULL
);

CREATE TABLE movimiento_usuario (
    id                        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario_del_movimiento BIGINT NOT NULL,
    tipo                      VARCHAR(255) NOT NULL,
    fecha                     DATE NOT NULL,
    id_usuario_que_movio      BIGINT NOT NULL,
    observaciones             VARCHAR(255),
    id_causa_baja             BIGINT,  -- solo aplica a bajas
    id_estancia_origen        BIGINT,  -- no aplica a altas
    id_estancia_destino       BIGINT   -- no aplica a bajas
);

CREATE TABLE aviso (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    asunto           VARCHAR(255) NOT NULL,
    tipo_aviso       VARCHAR(255) NOT NULL,
    id_usuario_envia BIGINT NOT NULL,
    mensaje          VARCHAR(255) NOT NULL,
    requiere_confirmacion BOOLEAN NOT NULL DEFAULT FALSE,  -- TRUE: cada destinatario debe confirmar lectura
    id_estancia      BIGINT  -- estancia a la que aplica; NULL = general (todas las estancias)
);

CREATE TABLE aviso_usuario (
    id_aviso   BIGINT NOT NULL,
    id_usuario BIGINT NOT NULL,
    leido      BOOLEAN NOT NULL DEFAULT FALSE,
    leido_en   TIMESTAMP(0) WITH TIME ZONE,  -- hora en que confirmo la lectura
    PRIMARY KEY (id_aviso, id_usuario)
);

-- ===================== Registros =====================

CREATE TABLE horario (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario    BIGINT NOT NULL,
    vigente_hasta DATE NOT NULL,
    vigente_desde DATE NOT NULL
);

CREATE TABLE horario_dia (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dia_de_semana VARCHAR(255) NOT NULL,
    id_horario    BIGINT NOT NULL,
    id_turno      BIGINT NOT NULL,
    id_sala       BIGINT NOT NULL
);

CREATE TABLE registro_entradas (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario_entrada  BIGINT NOT NULL,
    fecha_hora_entrada  TIMESTAMP(0) WITH TIME ZONE NOT NULL,
    fecha_hora_salida   TIMESTAMP(0) WITH TIME ZONE,  -- NULL hasta que sale
    id_ubicacion        BIGINT NOT NULL,
    origen_registro     VARCHAR(255) NOT NULL,
    id_usuario_registro BIGINT NOT NULL,
    id_sala             BIGINT NOT NULL,
    uuid                UUID NOT NULL,
    id_turno            BIGINT NOT NULL,
    dentro_de_zona      BOOLEAN NOT NULL  -- FALSE = "fuera de zona", la Responsable lo revisa
);

CREATE TABLE asistencia (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario_que_asistio BIGINT NOT NULL,
    estado                 VARCHAR(255) NOT NULL,
    fecha                  DATE NOT NULL,
    id_usuario_registro    BIGINT NOT NULL,
    id_estancia            BIGINT NOT NULL,
    id_motivo_ausencia     BIGINT  -- catalogo motivo_ausencia; obligatorio en falta/incidencia
);

-- Auditoria inmutable (append-only, R-08): quien hizo que y cuando, hora del servidor.
-- Se llena sola con triggers (ver al final); nadie la escribe directamente.
CREATE TABLE auditoria (
    id               BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    id_usuario       BIGINT,  -- autor; viene de app.id_usuario (lo fija la API). NULL si no se fijo
    accion           VARCHAR(255) NOT NULL,
    tabla            VARCHAR(255) NOT NULL,
    id_registro      BIGINT NOT NULL,
    datos_anteriores JSONB,  -- NULL en INSERT
    datos_nuevos     JSONB,  -- NULL en DELETE
    creado_en        TIMESTAMP(3) WITH TIME ZONE NOT NULL DEFAULT clock_timestamp()
);

